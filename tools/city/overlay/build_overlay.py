"""build_overlay: writes src/server/Systems/City/CityOverlay1..N.luau, the CityOverlay layer.

WHY: CityData1..N is generated by citygen.py (kept outside the repo, regenerated by other work):
it must never be edited by hand. Every whole-city fix (colours, z-fights, signs, wrapping props
into kit meshes...) is declared here instead, as operations on parts found by folder + name +
position, and City/init.luau applies them at load (applyOverlay, right after mergeAlleys). When
the city changes and a part is not found any more, that entry is skipped and the original stays.

    venv/bin/python -I tools/city/overlay/build_overlay.py            # build + validate + write
    venv/bin/python -I tools/city/overlay/build_overlay.py --check    # fail if the files are stale
    venv/bin/python -I tools/city/overlay/build_overlay.py --only demo --dry

Edit modules: tools/city/overlay/edits/*.py (one per area / family, run in name order), each
with a function edits(O); O is an overlay.core.Overlay (its docstring lists the ops). Every
match must hit exactly one built row: misses, ambiguous matches and refused removals stop the
build. The result is then applied to a fresh copy of the city exactly like the game does
(overlay/apply.py) and must apply with 0 skipped entries.
"""

import argparse
import copy
import importlib.util
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))  # tools/city: the overlay package, meshprop, citykit

from overlay import apply as overlay_apply  # noqa: E402
from overlay import citydata  # noqa: E402
from overlay.core import Overlay  # noqa: E402

EDITS_DIR = os.path.join(HERE, "edits")
PREFIX = "CityOverlay"
MAX_BYTES = 150_000
HEADER = (
    "--!strict\n"
    "-- GENERATED by tools/city/overlay/build_overlay.py — do not edit by hand.\n"
    "-- Piece {i} of {n} of the CityOverlay (a JSON text split in pieces): fixes declared in\n"
    "-- tools/city/overlay/edits/*.py, matched on the city's parts by folder + name + position.\n"
    "-- City/init.luau (applyOverlay) joins the pieces, applies them after the alleys.\n"
    "return [==["
)
FOOTER = "]==]\n"


def edit_modules(only=None):
    names = sorted(f[:-3] for f in os.listdir(EDITS_DIR)
                   if f.endswith(".py") and not f.startswith("_"))
    if only:
        wanted = set(only.split(","))
        missing = wanted - set(names)
        if missing:
            raise SystemExit(f"unknown edit module(s): {sorted(missing)} (have {names})")
        names = [n for n in names if n in wanted]
    out = []
    for n in names:
        spec = importlib.util.spec_from_file_location(f"overlay_edits_{n}", os.path.join(EDITS_DIR, f"{n}.py"))
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
        if not hasattr(mod, "edits"):
            raise SystemExit(f"edits/{n}.py has no function edits(O)")
        out.append((n, mod))
    return out


def build(only=None):
    data = citydata.merged()
    O = Overlay(data)
    for name, mod in edit_modules(only):
        O.module = name
        mod.edits(O)
    return O


def pieces(text):
    """The Luau files' contents for the JSON text (each <= MAX_BYTES)."""
    if "]==" in text:
        raise SystemExit("the overlay JSON contains ']==': it would close the Luau long string")
    room = MAX_BYTES - len(HEADER.format(i=99, n=99).encode()) - len(FOOTER)
    chunks, cur, size = [], [], 0
    for ch in text:  # (split on characters, counted in UTF-8 bytes)
        b = len(ch.encode())
        if size + b > room:
            chunks.append("".join(cur))
            cur, size = [], 0
        cur.append(ch)
        size += b
    chunks.append("".join(cur))
    n = len(chunks)
    return [HEADER.format(i=i + 1, n=n) + c + FOOTER for i, c in enumerate(chunks)]


def existing_files():
    out, i = [], 1
    while os.path.exists(os.path.join(citydata.CITY_DIR, f"{PREFIX}{i}.luau")):
        out.append(os.path.join(citydata.CITY_DIR, f"{PREFIX}{i}.luau"))
        i += 1
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="validate, and fail if the written files differ")
    ap.add_argument("--dry", action="store_true", help="validate only, write nothing")
    ap.add_argument("--only", help="comma list of edit modules (with --dry: try one module)")
    ap.add_argument("--verbose", "-v", action="store_true")
    a = ap.parse_args()
    if a.only and not (a.dry or a.check):
        raise SystemExit("--only writes a partial overlay: use it with --dry")

    O = build(a.only)
    for w in O.warnings:
        print("warning:", w)
    if O.errors:
        for e in O.errors:
            print("ERROR:", e)
        raise SystemExit(f"{len(O.errors)} error(s): nothing written")

    ov = O.json()
    text = json.dumps(ov, separators=(",", ":"), ensure_ascii=False)
    # the game's view: apply to a fresh copy, every entry must apply
    fresh = citydata.merged()
    before = len(fresh["parts"]) - len(fresh["skip"])
    lines = []
    stats = overlay_apply.apply(fresh, json.loads(text), lines)
    after = len(fresh["parts"]) - len(fresh["skip"])
    if stats["skipped"]:
        for eid, m, hits in stats["missed"]:
            print(f"ERROR: entry {eid}: {m} hit {hits} rows")
        raise SystemExit("the overlay does not apply cleanly to the current city")
    kinds = {}
    for e in ov["entries"]:
        for op in e["ops"]:
            kinds[op["op"]] = kinds.get(op["op"], 0) + 1
    print(f"[CityOverlay] {len(ov['entries'])} entries, {stats['ops']} ops {kinds}; "
          f"helpers {O.counts}; parts built {before} -> {after}; {len(text)} bytes of JSON")
    if a.verbose:
        for e in ov["entries"]:
            print(" ", e["id"], [op["op"] for op in e["ops"]])

    files = pieces(text)
    paths = [os.path.join(citydata.CITY_DIR, f"{PREFIX}{i + 1}.luau") for i in range(len(files))]
    if a.check:
        old = existing_files()
        stale = len(old) != len(paths)
        for p, content in zip(paths, files):
            if not os.path.exists(p):
                stale = True
                continue
            with open(p, encoding="utf-8") as f:
                stale = stale or f.read() != content
        if stale:
            raise SystemExit("CityOverlay*.luau is stale: run tools/city/overlay/build_overlay.py")
        print("[CityOverlay] up to date")
        return
    if a.dry:
        return
    for p, content in zip(paths, files):
        with open(p, "w", encoding="utf-8") as f:
            f.write(content)
    for p in existing_files()[len(paths):]:
        os.remove(p)
    print("wrote", ", ".join(f"{os.path.basename(p)} ({os.path.getsize(p)} B)" for p in paths))


def overlaid(data=None):
    """The merged city with the CURRENT CityOverlay files applied (what the game builds)."""
    data = data if data is not None else citydata.merged()
    ov = citydata.load(PREFIX)
    stats = overlay_apply.apply(data, copy.deepcopy(ov) if ov else None)
    return data, stats


if __name__ == "__main__":
    main()
